"""
Betfair Exchange - real adapter over betfairlightweight.

This is the feed that makes the wide market catalogue tradeable. The public
scoreboard feeds (ESPN and friends) carry match odds, spreads and totals and
almost nothing else. Betfair is where corners, cards, bookings, correct score,
half-time and Asian handicap markets actually have a two-sided price - and an
exchange price is a back AND a lay, which is what enables hedging and the
book-vs-exchange arbitrage the arb module models.

Hard rule, same as the rest of the betting subsystem: no credentials means no
markets. The old adapter returned five hardcoded football fixtures with prices
generated by `0.45 + i*0.05`. Those reached the scanner labelled as real
sports markets. This one returns an empty list and a diagnostic instead.

Betfair market types
--------------------
Betfair names its markets by a marketType code. The mapping below is the
bridge from those codes to this project's catalogue keys. Unknown codes are
reported rather than guessed, because misclassifying a market means settling
it against the wrong facts.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional, Sequence, Tuple

from loguru import logger

from ..markets.base import DataMode, Market, MarketSource, Token


